function Game.getMounts()
	local result = {}
	for mountId, mountData in pairs(mounts) do
		table.insert(result, {
			id = mountId,
			name = mountData.name,
			speed = mountData.speed,
			premium = mountData.premium,
		})
	end
	return result
end

function Game.getMountByLookType(id)
	local mount = mounts[id]
	if mount == nil then
		return nil
	end

	return {
		id = id,
		name = mount.name,
		speed = mount.speed,
		premium = mount.premium,
	}
end
